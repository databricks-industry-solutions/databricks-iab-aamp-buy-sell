#!/usr/bin/env python3
"""Render the registry Databricks App source dir (build/registry/).

Mirrors seller/render_apps.py: stamps the single ./registry codebase into
build/registry/ with its own app.yaml (target Lakebase instance from the prefix)
and a requirements.txt that pins the SDK from git. `make deploy PREFIX=<p>` runs
this then `databricks bundle deploy`.

build/ is gitignored and regenerated each deploy (so the instance prefix is never
baked into committed files). Databricks Apps only run `pip install -r requirements.txt`.
"""

from __future__ import annotations

import shutil
import sys
import textwrap
from pathlib import Path

SDK_PIN = "ad_seller_system @ git+https://github.com/IABTechLab/seller-agent.git@0b463ba"

HERE = Path(__file__).resolve().parent          # registry/
BUILD = HERE.parent / "build"


def render(prefix: str) -> None:
    base_reqs = (HERE / "requirements.txt").read_text()
    dst = BUILD / "registry"
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    shutil.copy(HERE / "app.py", dst / "app.py")
    shutil.copytree(HERE / "src", dst / "src")
    # Pre-built React console (vite build → frontend/dist). Built before render
    # (see `make frontend`); FastAPI serves it. API/MCP-only if absent.
    dist = HERE / "frontend" / "dist"
    if dist.exists():
        shutil.copytree(dist, dst / "frontend" / "dist")
    else:
        print(f"  ⚠ {dist} missing — run `make frontend` first (registry will serve API/MCP only)")
    (dst / "requirements.txt").write_text(base_reqs + f"\n# SDK (deploy install):\n{SDK_PIN}\n")
    (dst / "app.yaml").write_text(textwrap.dedent(f"""\
        # GENERATED by registry/render_apps.py — edit registry/ and re-render.
        command: ["python", "-m", "uvicorn", "app:app", "--host", "0.0.0.0", "--port", "8000"]
        env:
          - name: AAMP_REGISTRY_INSTANCE
            value: {prefix}-registry
          - name: AAMP_REGISTRY_DATABASE
            value: agent_registry
        """))
    print(f"✓ build/registry  (instance={prefix}-registry)")


if __name__ == "__main__":
    render(sys.argv[1] if len(sys.argv) > 1 else "aamp")
