#!/usr/bin/env python3
"""Render one Databricks App source dir per seller (each its own app + MCP server).

Databricks Apps require a UNIQUE source_code_path per app, so two seller apps can't
share ./seller. This stamps the single ./seller codebase into build/seller-<slug>/ —
one per seller — each with its own app.yaml (AAMP_SELLER + target Lakebase instance).
`make deploy PREFIX=<p>` runs this then `databricks bundle deploy`.

build/ is gitignored and regenerated each deploy (so the instance prefix is never
baked into committed files). The rendered requirements.txt pins the SDK from git
(Databricks Apps only run `pip install -r requirements.txt`).
"""

from __future__ import annotations

import shutil
import sys
import textwrap
from pathlib import Path

SELLERS = ["summit", "beacon"]
# Channel each seller advertises on its agent card (A2A inventory_types) so the registry
# carries it and buyers can match a campaign's channel to the right seller.
INVENTORY_TYPES = {"summit": "ctv", "beacon": "linear_tv"}
# Human-readable publisher name for the agent card (buyers show this, not the slug/org id).
DISPLAY_NAMES = {"summit": "Summit Streaming", "beacon": "Beacon Broadcast"}
SDK_PIN = "ad_seller_system @ git+https://github.com/IABTechLab/seller-agent.git@0b463ba"

HERE = Path(__file__).resolve().parent          # seller/
BUILD = HERE.parent / "build"


def render(prefix: str) -> None:
    base_reqs = (HERE / "requirements.txt").read_text()
    for slug in SELLERS:
        dst = BUILD / f"seller-{slug}"
        if dst.exists():
            shutil.rmtree(dst)
        dst.mkdir(parents=True)
        shutil.copy(HERE / "app.py", dst / "app.py")
        shutil.copytree(HERE / "src", dst / "src")
        # Pre-built React cockpit (vite build → frontend/dist). Apps only `pip install`,
        # so the UI must be built BEFORE render (see `make frontend`). FastAPI serves it.
        dist = HERE / "frontend" / "dist"
        if dist.exists():
            shutil.copytree(dist, dst / "frontend" / "dist")
        else:
            print(f"  ⚠ {dist} missing — run `make frontend` first (app will serve API/MCP only)")
        (dst / "requirements.txt").write_text(base_reqs + f"\n# SDK (deploy install):\n{SDK_PIN}\n")
        (dst / "app.yaml").write_text(textwrap.dedent(f"""\
            # GENERATED by seller/render_apps.py — edit seller/ and re-render.
            command: ["python", "-m", "uvicorn", "app:app", "--host", "0.0.0.0", "--port", "8000"]
            env:
              - name: AAMP_SELLER
                value: {slug}
              - name: AAMP_SELLER_INSTANCE
                value: {prefix}-seller
              - name: AAMP_SELLER_DATABASE
                value: ad_seller
              - name: AAMP_INVENTORY_TYPES
                value: {INVENTORY_TYPES.get(slug, "")}
              - name: AAMP_SELLER_DISPLAY_NAME
                value: {DISPLAY_NAMES.get(slug, "")}
            """))
        print(f"✓ build/seller-{slug}  (AAMP_SELLER={slug}, instance={prefix}-seller)")


if __name__ == "__main__":
    render(sys.argv[1] if len(sys.argv) > 1 else "aamp")
