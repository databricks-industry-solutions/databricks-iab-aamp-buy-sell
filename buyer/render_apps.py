#!/usr/bin/env python3
"""Render the buyer Databricks App source dir (build/buyer/).

Mirrors seller/registry render_apps.py: stamps the single ./buyer codebase into
build/buyer/ with its own app.yaml (target Lakebase instances from the prefix) and
vendors the IAB taxonomy TSVs the deployed app reads (TaxonomyLookupTool resolves
`<app>/resources/taxonomies`). `make deploy PREFIX=<p>` runs this then
`databricks bundle deploy`.

build/ is gitignored and regenerated each deploy, so the instance prefix is never
baked into committed files. Databricks Apps only run `pip install -r requirements.txt`.
"""

from __future__ import annotations

import os
import shutil
import sys
import textwrap
from pathlib import Path
from typing import Optional

HERE = Path(__file__).resolve().parent          # buyer/
REPO = HERE.parent                               # IAB_AAMP_DEMO/
BUILD = REPO / "build"


def _resolve_registry_url(prefix: str, profile: Optional[str]) -> Optional[str]:
    """Best-effort: the deployed registry app's URL (so the buyer runs against the live
    registry). The app exists only after the first deploy, so this returns None on a
    first-ever bring-up — the buyer then uses the Lakebase fallback until re-rendered
    (run `make wire-buyer` after the registry exists, or just re-deploy)."""
    try:
        from databricks.sdk import WorkspaceClient

        w = WorkspaceClient(profile=profile) if profile and profile != "DEFAULT" else WorkspaceClient()
        return w.apps.get(name=f"{prefix}-registry-app").url.rstrip("/")
    except Exception:
        return None


def render(prefix: str, profile: Optional[str] = None) -> None:
    dst = BUILD / "buyer"
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    shutil.copy(HERE / "app.py", dst / "app.py")
    shutil.copy(HERE / "requirements.txt", dst / "requirements.txt")
    shutil.copytree(HERE / "src", dst / "src")
    shutil.copytree(HERE / "static", dst / "static")

    # The built React console (app.py serves it over the legacy static page when
    # present — `make frontend` builds it; without it the app falls back gracefully).
    ui_dist = HERE / "frontend" / "dist"
    if ui_dist.is_dir():
        shutil.copytree(ui_dist, dst / "frontend" / "dist")
    else:
        print("  ⚠ buyer/frontend/dist missing — run `make frontend` (legacy UI will serve)")

    # Vendor the IAB taxonomy TSVs so the deployed app validates audience codes
    # (the app tree is its only filesystem; taxonomy.py looks under <app>/resources).
    tsvs = REPO / "resources" / "taxonomies"
    if tsvs.is_dir() and any(tsvs.glob("*.tsv")):
        shutil.copytree(tsvs, dst / "resources" / "taxonomies")
    else:
        print(f"  ⚠ {tsvs} has no TSVs — run `make taxonomies SDK_DIR=...` first "
              f"(audience planning will run unvalidated)")

    registry_url = _resolve_registry_url(prefix, profile)
    if registry_url:
        # Live registry: the buyer discovers sellers (by their card's inventory_types) and
        # verifies its own trust against the registry app instead of reading Lakebase.
        registry_block = f"""\
          - name: AAMP_REGISTRY_URL
            value: {registry_url}"""
    else:
        # No registry app yet (first-ever deploy): the buyer uses the Lakebase fallback
        # until re-rendered against the live registry — see `make wire-buyer`.
        registry_block = f"""\
          # Live registry app not found at render time — buyer uses the Lakebase fallback.
          # Run `make wire-buyer` once the {prefix}-registry-app exists to bake its URL here.
          # - name: AAMP_REGISTRY_URL
          #   value: https://<{prefix}-registry-app url>"""

    (dst / "app.yaml").write_text(textwrap.dedent(f"""\
        # GENERATED by buyer/render_apps.py — edit buyer/ and re-render.
        command: ["python", "-m", "uvicorn", "app:app", "--host", "0.0.0.0", "--port", "8000"]
        env:
          - name: AAMP_BUYER_ID
            value: buyer-northstar
          - name: AAMP_BUYER_INSTANCE
            value: {prefix}-buyer
          - name: AAMP_BUYER_DATABASE
            value: ad_buyer
          - name: AAMP_REGISTRY_INSTANCE
            value: {prefix}-registry
          - name: AAMP_REGISTRY_DATABASE
            value: agent_registry
          - name: AAMP_DEFAULT_SSP
            value: {os.environ.get("AAMP_DEFAULT_SSP", "Magnite")}
{registry_block}
        """))
    mode = f"registry_url={registry_url}" if registry_url else "Lakebase fallback (no registry app yet)"
    print(f"✓ build/buyer  (buyer={prefix}-buyer, registry={prefix}-registry, {mode})")


if __name__ == "__main__":
    render(
        sys.argv[1] if len(sys.argv) > 1 else "aamp",
        sys.argv[2] if len(sys.argv) > 2 else None,
    )
